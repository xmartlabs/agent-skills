#!/usr/bin/env bash
DIR="$(cd "$(dirname "$0")/.." && pwd)"
. "$DIR/tests/helper.sh"
. "$DIR/skills/pr-evidence/scripts/lib/origin.sh"
echo "origin_test:"
assert_ok   "bare localhost"        is_test_origin "localhost"
assert_ok   "localhost:port+scheme" is_test_origin "http://localhost:3001"
assert_ok   "127.0.0.1:port"        is_test_origin "http://127.0.0.1:3000/catalog"
assert_ok   "127.x loopback"        is_test_origin "http://127.9.9.9"
assert_ok   "ipv6 loopback"         is_test_origin "http://[::1]:3000"
assert_ok   "0.0.0.0"               is_test_origin "http://0.0.0.0:8080"
assert_ok   ".test tld"             is_test_origin "http://myapp.test"
assert_ok   ".localhost tld"        is_test_origin "http://web.localhost:5173"
assert_ok   "10/8 private"          is_test_origin "http://10.1.2.3:3000"
assert_ok   "192.168/16 private"    is_test_origin "http://192.168.1.5"
assert_ok   "172.16/12 low"         is_test_origin "http://172.16.0.1"
assert_ok   "172.16/12 high"        is_test_origin "http://172.31.255.254"
assert_ok   "uppercase host"        is_test_origin "http://LOCALHOST:3001"
assert_fail "public domain"         is_test_origin "https://app.example.com"
assert_fail "172.32 outside range"  is_test_origin "http://172.32.0.1"
assert_fail "public bare host"      is_test_origin "https://staging.acme.io/x"
assert_fail "empty"                 is_test_origin ""
# prefix-glob bypass: registrable domains that merely start with an allowed IP label
assert_fail "127 prefix bypass"     is_test_origin "http://127.0.0.1.evil.com"
assert_fail "10 prefix bypass"      is_test_origin "http://10.evil.com"
assert_fail "192.168 prefix bypass" is_test_origin "http://192.168.1.1.evil.com"
assert_fail "172.16 prefix bypass"  is_test_origin "http://172.16.0.1.evil.com"
assert_fail "127 non-numeric host"  is_test_origin "http://127.foo.bar"
# userinfo forgery via query/fragment: '@' must only be honored inside the authority
assert_fail "userinfo via query"    is_test_origin "http://evil.com?@localhost"
assert_fail "userinfo via fragment" is_test_origin "http://evil.com#@localhost"
assert_fail "real userinfo to evil" is_test_origin "http://localhost@evil.com"
assert_fail "localhost as subdomain of evil" is_test_origin "http://localhost.evil.com"
# alternate IP encodings must NOT match the private/loopback globs (fail-closed regression guards)
assert_fail "decimal loopback"      is_test_origin "http://2130706433"
assert_fail "octal octet"           is_test_origin "http://0177.0.0.1"
assert_fail "hex octet"             is_test_origin "http://0x7f.0.0.1"
assert_fail "ipv4-mapped ipv6 meta" is_test_origin "http://[::ffff:169.254.169.254]"
assert_fail "cloud metadata ip"     is_test_origin "http://169.254.169.254"
finish_tests
